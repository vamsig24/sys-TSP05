#!/usr/bin/env python3
"""Turn characterization/<sensor>.csv (from `scripts/tsp05 characterize`)
into transfer function plots, error plots and an error table.

    python3 scripts/analyze_characterization.py

Writes characterization/<sensor>_transfer.png, <sensor>_error.png and
characterization/results.md, and prints fitted conversion constants.
"""

import csv
import math
import os

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'characterization')

# x label, unit, raw field (y axis of the transfer function), raw label
SENSORS = {
    'sharp': ('True distance', 'cm', 'sharp_v', 'Output voltage (V)'),
    'flex': ('True bend angle', 'deg', 'flex_adc', 'ADC counts (filtered)'),
    'pot': ('True shaft angle', 'deg', 'pot_raw', 'ADC counts'),
    'tof': ('True distance', 'cm', 'tof_mm', 'Reported distance (mm)'),
}


def load(name):
    path = os.path.join(DIR, f'{name}.csv')
    if not os.path.exists(path):
        return None
    with open(path) as f:
        rows = [r for r in csv.DictReader(f)]
    data = {k: np.array([float(r[k]) for r in rows]) for k in rows[0]} if rows else {}
    if not data:
        return None
    order = np.argsort(data['true'])
    return {k: v[order] for k, v in data.items()}


def fit_text(name, d):
    """Fitted conversion constants from the measurements."""
    x = d['true']
    if name == 'flex':
        slope, r0 = np.polyfit(x, d['flex_kohm'], 1)
        return (f'R = {r0:.2f} kOhm + {slope:.4f} kOhm/deg x angle  ->  '
                f'protocol.py: FLEX_R0_KOHM = {r0:.2f}, FLEX_KOHM_PER_DEG = {slope:.4f}')
    if name == 'pot':
        slope, v0 = np.polyfit(x, d['pot_v'], 1)
        return (f'V = {v0:.3f} V + {slope * 1000:.3f} mV/deg x angle  ->  '
                f'protocol.py: POT_RANGE_DEG = {5.0 / slope:.0f}')
    if name == 'sharp':
        ok = d['sharp_v'] > 0
        b, log_a = np.polyfit(np.log(d['sharp_v'][ok]), np.log(x[ok]), 1)
        return (f'distance = {math.exp(log_a):.3f} x V^{b:.4f}  '
                '(firmware uses 27.728 x V^-1.2045)')
    if name == 'tof':
        slope, off = np.polyfit(x, d['measured'], 1)
        return f'reported = {slope:.4f} x true {off:+.2f} cm'
    return ''


def plot_transfer(name, d):
    xlabel, unit, raw, ylabel = SENSORS[name]
    fig, ax = plt.subplots(figsize=(6.4, 4.2))
    ax.errorbar(d['true'], d[raw], yerr=d.get(f'{raw}_std'), fmt='o-',
                color='#1f77b4', ecolor='#888', capsize=3, label='Measured')
    ax.set_xlabel(f'{xlabel} ({unit})')
    ax.set_ylabel(ylabel)
    ax.set_title(f'{name}: transfer function (own measurements)')
    ax.grid(alpha=0.3)
    if raw in ('flex_adc', 'pot_raw'):
        sec = ax.secondary_yaxis('right', functions=(lambda a: a * 5 / 1023,
                                                     lambda v: v * 1023 / 5))
        sec.set_ylabel('Voltage (V)')
    ax.legend()
    fig.tight_layout()
    out = os.path.join(DIR, f'{name}_transfer.png')
    fig.savefig(out, dpi=150)
    plt.close(fig)
    return out


def plot_error(name, d):
    xlabel, unit, _, _ = SENSORS[name]
    fig, ax = plt.subplots(figsize=(6.4, 3.6))
    ax.axhline(0, color='#888', lw=1)
    ax.errorbar(d['true'], d['error'], yerr=d['measured_std'], fmt='o-',
                color='#d62728', ecolor='#888', capsize=3)
    ax.set_xlabel(f'{xlabel} ({unit})')
    ax.set_ylabel(f'Measured - true ({unit})')
    ax.set_title(f'{name}: conversion error')
    ax.grid(alpha=0.3)
    fig.tight_layout()
    out = os.path.join(DIR, f'{name}_error.png')
    fig.savefig(out, dpi=150)
    plt.close(fig)
    return out


def main():
    report = ['# Sensor characterization results', '',
              'Generated by `scripts/analyze_characterization.py` from '
              '`scripts/tsp05 characterize` measurements.', '']
    summary = ['| Sensor | Range | Points | Mean abs error | RMS error | Max abs error |',
               '|---|---|---|---|---|---|']
    details = []
    found = False

    for name, (xlabel, unit, raw, _) in SENSORS.items():
        d = load(name)
        if d is None:
            print(f'{name}: no data (run scripts/tsp05 characterize {name})')
            continue
        found = True
        ok = ~np.isnan(d['error'])
        err = d['error'][ok]
        mae, rms, mx = (np.mean(np.abs(err)), np.sqrt(np.mean(err ** 2)),
                        np.max(np.abs(err)))
        rng = f"{d['true'].min():g}-{d['true'].max():g} {unit}"
        summary.append(f'| {name} | {rng} | {ok.sum()} | {mae:.2f} {unit} | '
                       f'{rms:.2f} {unit} | {mx:.2f} {unit} |')

        transfer = plot_transfer(name, d) if name != 'tof' else None
        error_png = plot_error(name, d)
        fit = fit_text(name, d)

        details += [f'## {name}', '']
        if transfer:
            details += [f'![{name} transfer function]({os.path.basename(transfer)})', '']
        details += [f'![{name} error]({os.path.basename(error_png)})', '',
                    f'Fit: {fit}', '',
                    f'| True ({unit}) | Measured ({unit}) | Error ({unit}) | {raw} |',
                    '|---|---|---|---|']
        for i in range(len(d['true'])):
            details.append(f"| {d['true'][i]:g} | {d['measured'][i]:.2f} | "
                           f"{d['error'][i]:+.2f} | {d[raw][i]:.3f} |")
        details.append('')

        print(f'{name}: {ok.sum()} points, mean |error| {mae:.2f} {unit}, '
              f'RMS {rms:.2f} {unit}, max {mx:.2f} {unit}')
        print(f'  fit: {fit}')

    if not found:
        return 1
    with open(os.path.join(DIR, 'results.md'), 'w') as f:
        f.write('\n'.join(report + summary + [''] + details))
    print(f'\nWrote {os.path.normpath(DIR)}/results.md and *_transfer.png / *_error.png')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
